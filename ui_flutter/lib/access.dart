/// Права ключа: тот же список, что читает браузерный клиент.

/// GET /whoami называет скоупы предъявленного ключа (app/http/server.py:
/// _serve_whoami, docs/SERVER-CLIENT.md §4). Браузер делает это в `fetchAccess`
/// (ui_src/app.js:816) и подписывает недоступные цели до запроса, а не тыкает
/// 403 на каждую кнопку; Flutter повторяет то же поведение: кнопка с
/// невыданным правом называется текстом, а не молча уходит в отказ.
///
/// Пустой список прав - это «прав нет», а не «прав ноль по молчанию»: отказ
/// сервера (401 «не привязан», 403, битый ответ) лежит в `refusal` и называется
/// текстом из словаря бэкенда (app/i18n.py: http.pairing, http.scope), сверяемым
/// tools/check_flutter_mirror.py - текст не выдумывается на стороне клиента.
library;

/// Тексты отказа - значения i18n ru (app/i18n.py); сверка ведётся стражем.
const String kScopeDeniedText = 'право не выдано сервером';
const String kUnpairedText = 'ключ доступа не принят - привязка не завершена';

/// Список прав ключа и причина, по которой список не прочитан.
class Access {
  Access({this.scopes = const <String>[], this.refusal});

  /// Скоупы, выданные ключу (app/http/scopes.py: SCOPES).
  final List<String> scopes;

  /// Причина, по которой прав не прочитано (401/403/битый ответ). `null` -
  /// список прочитан и он пуст: это «прав нет», и она называется.
  final String? refusal;

  /// Право выдано? Когда список не прочитан, ответ - «нет» с причиной:
  /// молчаливое «да» на непрочитанных правах было бы худшим вариантом.
  bool has(String scope) => refusal == null && scopes.contains(scope);

  /// Текст отказа для цели, требующей право. Называет причину чтения прав,
  /// если прав не прочитано, и отсутствие права - если прочитано.
  String denial(String scope) => refusal ?? kScopeDeniedText;
}
